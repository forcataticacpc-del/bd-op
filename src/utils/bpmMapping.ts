function normalizeBPMText(str: string): string {
  if (!str) return '';
  return str
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9\s]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Identifica o Batalhão (BPM) a partir do endereço completo ou nome do bairro
 */
export function detectBPM(addressOrNeighborhood: string): string {
  if (!addressOrNeighborhood) return '';
  const normalizedInput = normalizeBPMText(addressOrNeighborhood);
  if (!normalizedInput) return '';

  // Procura por correspondência exata ou de substrings mais longas primeiro
  let bestMatchBpm = '';
  let maxMatchedLength = 0;

  for (const group of BPM_DATA) {
    for (const b of group.bairros) {
      const normBairro = normalizeBPMText(b);
      if (!normBairro) continue;

      // Verifica se o bairro é uma palavra ou frase completa contida no texto
      const regex = new RegExp(`\\b${normBairro}\\b`, 'i');
      if (regex.test(normalizedInput)) {
        if (normBairro.length > maxMatchedLength) {
          maxMatchedLength = normBairro.length;
          bestMatchBpm = group.bpm;
        }
      }
    }
  }

  return bestMatchBpm;
}
